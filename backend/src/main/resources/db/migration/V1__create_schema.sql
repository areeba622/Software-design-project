-- =============================================================================
-- Palette — baseline schema
-- Replaces the old "hibernate ddl-auto=update" schema, which had drifted and
-- picked up duplicate columns (width/width_ft, amountpkr/amount_inpkr, ...).
-- Written in portable SQL so it runs on PostgreSQL and on H2 (used in tests).
-- All money columns are in PKR unless the name says otherwise.
-- =============================================================================

CREATE TABLE aesthetic_styles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(500)
);

CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               VARCHAR(255) NOT NULL UNIQUE,
    full_name           VARCHAR(255) NOT NULL,
    password_hash       VARCHAR(255) NOT NULL,
    currency_preference VARCHAR(255) NOT NULL
);

CREATE TABLE furniture_bundles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    description     VARCHAR(255),
    room_type       VARCHAR(255) NOT NULL,
    style_id        BIGINT       NOT NULL REFERENCES aesthetic_styles (id),
    discount_factor DOUBLE PRECISION NOT NULL,
    total_price_pkr DOUBLE PRECISION NOT NULL
);

CREATE TABLE products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    description     VARCHAR(500),
    price_pkr       DOUBLE PRECISION NOT NULL,
    image_url       VARCHAR(255),
    category        VARCHAR(255),
    room_type       VARCHAR(255),
    aesthetic_style VARCHAR(255),
    vendor_name     VARCHAR(255),
    bundle_id       BIGINT REFERENCES furniture_bundles (id)
);

CREATE TABLE designers (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(255) NOT NULL,
    email              VARCHAR(255) NOT NULL UNIQUE,
    bio                VARCHAR(500),
    portfolio_url      VARCHAR(500),
    hourly_rate_pkr    DOUBLE PRECISION NOT NULL,
    specialty          VARCHAR(255) NOT NULL,
    preferred_style_id BIGINT NOT NULL REFERENCES aesthetic_styles (id)
);

CREATE TABLE carts (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE custom_rooms (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    room_type       VARCHAR(255) NOT NULL,
    width           INTEGER      NOT NULL,
    length          INTEGER      NOT NULL,
    flooring        VARCHAR(255),
    wallpaper       VARCHAR(255),
    total_price_pkr DOUBLE PRECISION NOT NULL,
    is_finalized    BOOLEAN      NOT NULL,
    created_at      TIMESTAMP    NOT NULL
);

CREATE TABLE custom_room_furniture (
    room_id        BIGINT NOT NULL REFERENCES custom_rooms (id) ON DELETE CASCADE,
    furniture_item VARCHAR(255)
);

CREATE TABLE cart_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id        BIGINT       NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
    item_type      VARCHAR(255) NOT NULL,
    product_id     BIGINT REFERENCES products (id),
    bundle_id      BIGINT REFERENCES furniture_bundles (id),
    custom_room_id BIGINT REFERENCES custom_rooms (id) ON DELETE CASCADE,
    designer_id    BIGINT REFERENCES designers (id),
    quantity       INTEGER      NOT NULL,
    unit_price_pkr DOUBLE PRECISION NOT NULL
);

CREATE TABLE orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status          VARCHAR(255) NOT NULL,
    grand_total_pkr DOUBLE PRECISION NOT NULL,
    created_at      TIMESTAMP    NOT NULL
);

CREATE TABLE order_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    item_type      VARCHAR(255) NOT NULL,
    item_name      VARCHAR(255) NOT NULL,
    quantity       INTEGER      NOT NULL,
    unit_price_pkr DOUBLE PRECISION NOT NULL,
    line_total_pkr DOUBLE PRECISION NOT NULL
);

CREATE TABLE payments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT       NOT NULL UNIQUE REFERENCES orders (id) ON DELETE CASCADE,
    status         VARCHAR(255) NOT NULL,
    gateway        VARCHAR(255),
    amount_pkr     DOUBLE PRECISION NOT NULL,
    amount_usd     DOUBLE PRECISION,
    transaction_id VARCHAR(255),
    created_at     TIMESTAMP    NOT NULL
);

CREATE TABLE design_quizzes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    selected_style     VARCHAR(255) NOT NULL,
    selected_room_type VARCHAR(255) NOT NULL,
    created_at         TIMESTAMP    NOT NULL
);

-- Foreign-key lookups used by the repositories
CREATE INDEX idx_products_category      ON products (category);
CREATE INDEX idx_products_room_type     ON products (room_type);
CREATE INDEX idx_products_bundle        ON products (bundle_id);
CREATE INDEX idx_cart_items_cart        ON cart_items (cart_id);
CREATE INDEX idx_custom_rooms_user      ON custom_rooms (user_id);
CREATE INDEX idx_orders_user            ON orders (user_id);
CREATE INDEX idx_order_items_order      ON order_items (order_id);
CREATE INDEX idx_design_quizzes_user    ON design_quizzes (user_id);
CREATE INDEX idx_custom_room_furniture  ON custom_room_furniture (room_id);
